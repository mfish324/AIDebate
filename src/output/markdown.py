"""Markdown export for debate results"""

from __future__ import annotations

import os
import re
from datetime import datetime
from pathlib import Path
from typing import TYPE_CHECKING

from slugify import slugify

if TYPE_CHECKING:
    from ..debate.orchestrator import DebateResult
    from ..debate.voting import VoteResults


PROVIDER_NAMES = {
    "claude": "Claude",
    "openai": "GPT-4",
    "groq": "Llama",
}


class MarkdownExporter:
    """Exports debate results to markdown format"""

    def __init__(self, output_dir: str = "debates"):
        self.output_dir = Path(output_dir)
        self.output_dir.mkdir(parents=True, exist_ok=True)

    def generate_filename(self, question: str, timestamp: datetime) -> str:
        """Generate filename from question and timestamp"""
        date_str = timestamp.strftime("%Y-%m-%d_%H-%M-%S")
        slug = slugify(question[:50], max_length=50)
        return f"debate_{date_str}_{slug}.md"

    def export(self, result: DebateResult) -> str:
        """Export debate result to markdown file"""
        filename = self.generate_filename(result.question, result.started_at)
        filepath = self.output_dir / filename

        content = self._generate_markdown(result)

        with open(filepath, "w", encoding="utf-8") as f:
            f.write(content)

        return str(filepath)

    def _generate_markdown(self, result: DebateResult) -> str:
        """Generate markdown content"""
        lines = []

        # Title
        lines.append(f"# 🤖 AI Debate: {result.question}")
        lines.append("")
        lines.append(
            f"**Date:** {result.started_at.strftime('%Y-%m-%d %H:%M:%S')}"
        )
        lines.append(
            f"**Duration:** {result.duration_seconds:.1f} seconds"
        )
        lines.append(
            f"**Participants:** {', '.join(PROVIDER_NAMES.get(p, p) for p in result.participating_providers)}"
        )
        lines.append("")
        lines.append("---")
        lines.append("")

        # Table of Contents
        lines.append("## 📑 Table of Contents")
        lines.append("")
        lines.append("- [Phase 1: Initial Responses](#phase-1-initial-responses)")
        lines.append("- [Phase 2: Cross-Review](#phase-2-cross-review)")
        lines.append("- [Phase 3: Final Positions](#phase-3-final-positions)")
        lines.append("- [Voting Results](#voting-results)")
        lines.append("- [Final Verdict](#final-verdict)")
        lines.append("- [Cost Summary](#cost-summary)")
        lines.append("")

        # Phase 1: Initial Responses
        lines.append("## Phase 1: Initial Responses")
        lines.append("")
        lines.extend(self._format_phase("initial", result))
        lines.append("")

        # Phase 2: Cross-Review
        lines.append("## Phase 2: Cross-Review")
        lines.append("")
        lines.extend(self._format_phase("review", result))
        lines.append("")

        # Phase 3: Final Positions
        lines.append("## Phase 3: Final Positions")
        lines.append("")
        lines.extend(self._format_phase("final", result))
        lines.append("")

        # Voting Results
        lines.append("## 🗳️ Voting Results")
        lines.append("")
        if result.vote_results:
            lines.extend(self._format_votes(result.vote_results))
        else:
            lines.append("*No voting results available*")
        lines.append("")

        # Final Verdict
        lines.append("## 🏆 Final Verdict")
        lines.append("")
        if result.verdict:
            lines.append(result.verdict)
        else:
            lines.append("*No verdict available*")
        lines.append("")

        # Cost Summary
        lines.append("## 💰 Cost Summary")
        lines.append("")
        if result.cost_summary:
            lines.extend(self._format_costs(result.cost_summary))
        else:
            lines.append("*No cost data available*")
        lines.append("")

        # Errors
        if result.errors:
            lines.append("## ⚠️ Errors")
            lines.append("")
            for error in result.errors:
                lines.append(f"- {error}")
            lines.append("")

        # Footer
        lines.append("---")
        lines.append("")
        lines.append(
            "*Generated by Multi-AI Debate System*"
        )

        return "\n".join(lines)

    def _format_phase(self, phase_name: str, result: DebateResult) -> list[str]:
        """Format a single phase's responses"""
        lines = []
        phase = result.phases.get(phase_name)

        if not phase:
            lines.append("*No data for this phase*")
            return lines

        for provider, response in phase.responses.items():
            name = PROVIDER_NAMES.get(provider, provider)

            lines.append(f"<details>")
            lines.append(f"<summary><strong>{name}</strong></summary>")
            lines.append("")

            if response.success:
                # Escape any code blocks properly
                content = self._format_content(response.content)
                lines.append(content)
            else:
                lines.append(f"*Error: {response.error}*")

            lines.append("")
            lines.append(f"*Tokens: {response.input_tokens} in / {response.output_tokens} out | Latency: {response.latency_ms:.0f}ms*")
            lines.append("")
            lines.append("</details>")
            lines.append("")

        return lines

    def _format_content(self, content: str) -> str:
        """Format content for markdown, handling code blocks"""
        # Content should already be markdown-compatible
        # Just ensure code blocks are preserved
        return content

    def _format_votes(self, votes: VoteResults) -> list[str]:
        """Format voting results as a table"""
        lines = []

        # Get all providers
        all_providers = set()
        for tally in [
            votes.best_overall_tally,
            votes.most_accurate_tally,
            votes.most_practical_tally,
        ]:
            all_providers.update(tally.keys())

        providers = sorted(all_providers)
        if not providers:
            lines.append("*No votes recorded*")
            return lines

        # Header
        header = "| Category |"
        separator = "|----------|"
        for p in providers:
            name = PROVIDER_NAMES.get(p, p)
            header += f" {name} |"
            separator += "--------|"

        lines.append(header)
        lines.append(separator)

        # Rows
        def format_row(name: str, tally: dict[str, int]) -> str:
            row = f"| {name} |"
            for p in providers:
                votes = tally.get(p, 0)
                row += f" {votes} vote{'s' if votes != 1 else ''} |"
            return row

        lines.append(format_row("Best Overall", votes.best_overall_tally))
        lines.append(format_row("Most Accurate", votes.most_accurate_tally))
        lines.append(format_row("Most Practical", votes.most_practical_tally))

        lines.append("")

        # Winner and confidence
        winner = votes.get_overall_winner()
        confidence = votes.calculate_confidence()
        confidence_level = (
            "High" if confidence > 0.7 else "Medium" if confidence > 0.4 else "Low"
        )

        if winner:
            winner_name = PROVIDER_NAMES.get(winner, winner)
            lines.append(f"**Overall Winner:** {winner_name}")

        lines.append(f"**Agreement Level:** {confidence_level} ({confidence:.0%})")

        return lines

    def _format_costs(self, cost_summary: dict) -> list[str]:
        """Format cost summary"""
        lines = []

        total_cost = cost_summary.get("total_cost", 0)
        total_tokens = cost_summary.get("total_tokens", 0)

        lines.append(f"**Total Cost:** ${total_cost:.4f}")
        lines.append(f"**Total Tokens:** {total_tokens:,}")
        lines.append("")

        by_provider = cost_summary.get("by_provider", {})
        if by_provider:
            lines.append("### By Provider")
            lines.append("")
            lines.append("| Provider | Input Tokens | Output Tokens | Cost |")
            lines.append("|----------|-------------|---------------|------|")

            for provider, stats in by_provider.items():
                name = PROVIDER_NAMES.get(provider, provider)
                lines.append(
                    f"| {name} | {stats['input_tokens']:,} | "
                    f"{stats['output_tokens']:,} | ${stats['total_cost']:.4f} |"
                )

        return lines
